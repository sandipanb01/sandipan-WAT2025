# Sample some sentences safely
def sample_texts_safe(stream_iterable, n_samples=20):
    samples = []
    for idx, item in enumerate(stream_iterable):
        if len(samples) >= n_samples:
            break
        try:
            text = item["text"]
            if isinstance(text, bytes):
                text = text.decode("utf-8", errors="ignore")  # ignore broken bytes
            samples.append(text)
        except Exception:
            continue
    return samples

hin_samples = sample_texts_safe(hin_stream, n_samples=20)
print("Hindi samples:", hin_samples[:5])

def batch_translate_no_cache(sentences, src_lang, tgt_lang, model, tokenizer, ip):
    inputs = ip.preprocess_batch(sentences, src_lang=src_lang, tgt_lang=tgt_lang)
    model_inputs = tokenizer(
        inputs, return_tensors="pt", padding=True, truncation=True
    ).to(model.device)
    translated_tokens = model.generate(**model_inputs, use_cache=False, max_length=256)
    outputs = tokenizer.batch_decode(translated_tokens, skip_special_tokens=True)
    return ip.postprocess_batch(outputs, lang=tgt_lang)

print("[INFO] Backtranslating Hindi → English ...")
BATCH_SIZE = 16
backtranslated_eng = []

for i in range(0, len(hin_samples), BATCH_SIZE):
    batch = hin_samples[i:i+BATCH_SIZE]
    translations = batch_translate_no_cache(
        batch,
        src_lang="hin_Deva",
        tgt_lang="eng_Latn",
        model=en_hi_model,
        tokenizer=en_hi_tokenizer,
        ip=ip
    )
    backtranslated_eng.extend(translations)

